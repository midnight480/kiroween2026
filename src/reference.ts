const COMMON = `Every resource also accepts these items:

| Item | Becomes | Notes |
|---|---|---|
| \`DEPENDS-ON\` | \`DependsOn\` | the name of another resource in the same file, or several separated by commas |
| \`DELETION-POLICY\` | \`DeletionPolicy\` | \`Delete\`, \`Retain\` or \`Snapshot\` |
| \`NAME-TAG\` | a \`Name\` tag | only on resource types that take tags (marked below) |`;

const cell = (text: string): string => text.replaceAll("|", "\\|");

function allowed(f: Field): string {
  if (f.map) return Object.keys(f.map).map((k) => `\`${k}\``).join(", ");
  if (f.enum) return f.enum.map((v) => `\`${v}\``).join(", ");
  return "";
}

function show(value: unknown): string {
  if (value === undefined) return "";
  return `\`${typeof value === "string" ? value : JSON.stringify(value)}\``;
}

function fieldRow(f: Field): string {
  return `| \`${f.name}\` | \`${cell(f.cfn)}\` | ${KIND[f.kind]} | ${f.required ? "yes" : ""} | ${cell(allowed(f))} | ${cell(show(f.default))} |`;
}

const HEADER = "| Item | CloudFormation property | Type | Required | Allowed values | Default |\n|---|---|---|---|---|---|";

/**
 * 実行時の値だけでできている文面（`${name}（${port}）が…`）は、文書では意味が通らない。
 * そのコードだけ、文書用の説明に置き換える。
 */
const EXPLAIN: Record<string, string> = {
  "OPEN-TO-THE-WORLD":
    "an ingress rule open to `0.0.0.0/0` covers SSH (22), RDP (3389), MySQL (3306) or PostgreSQL (5432). This includes protocol `-1` and port ranges that contain one of them. A cursed wildcard.",
};

/** `post` の中の h.warn / h.fail を、ソースの文字列から取り出す。メッセージは英語に直す。 */
export function rulesFrom(block: string): string[] {
  const out: string[] = [];
  for (const m of block.matchAll(/h\.(warn|fail)\(\s*"([A-Z0-9-]+)",\s*(`[^`]*`|"(?:[^"\\]|\\.)*")/g)) {
    const kind = m[1] === "fail" ? "Error" : "Warning";
    const japanese = (m[3] as string).slice(1, -1).replaceAll('\\"', '"');
    // 実行時の値（${...}）は、文中に <value> として残す
    const english = localize(japanese.replace(/\$\{[^}]*\}/g, "<value>"), "en");
    out.push(`- ${kind} \`${m[2]}\`: ${EXPLAIN[m[2] as string] ?? english}`);
  }
  return out;
}

function listBlock(list: ListSpec): string {
  const rows = list.fields.map((f) => `| \`...${f.name}\` | \`${cell(f.cfn)}\` | ${KIND[f.kind]} | ${f.required ? "yes" : ""} | ${cell(allowed(f))} | ${cell(show(f.default))} |`);
  return `**Table: an \`OCCURS\` group whose name ends in \`${list.group}\`.** It becomes the \`${list.cfn}\` array, one object per row. The group's items have names that *end in* the suffixes below. Fill them with \`MOVE\` and a subscript.\n\n${HEADER.replace("| Item |", "| Item (suffix) |")}\n${rows.join("\n")}`;
}

export interface SourceFiles {
  /** src/mapping/*.ts の中身（ファイル名 → 文字列） */
  [file: string]: string;
}

const AREAS: Array<[string, string]> = [
  ["network.ts", "Network and edge"],
  ["compute.ts", "Compute"],
  ["database.ts", "Databases"],
  ["containers.ts", "Containers"],
  ["messaging.ts", "Messaging"],
];

/** その型の定義ブロック（`type: "X",` から次の `type: "` の手前まで）を、ファイルの文字列から切り出す。 */
function blockOf(source: string, type: string): string {
  const start = source.indexOf(`type: "${type}"`);
  if (start < 0) return "";
  const next = source.indexOf('\n    type: "', start + 10);
  return source.slice(start, next < 0 ? source.length : next);
}

export function renderReference(specs: ReadonlyMap<string, ResourceSpec>, sources: SourceFiles): string {
  const out: string[] = [];
  const total = specs.size + 6;

  out.push(`# Resource reference

> **Generated** from the mapping tables in \`src/mapping/\` by \`npm run docs:reference\`. Do not edit by hand: \`npx vitest\` fails if this file is out of date.

${total} AWS resource types can be written in COBOL: ${specs.size} from a table, and 6 with hand-written code (the S3 bucket, the IAM role and managed policy, the Lambda function, and the DynamoDB table and global table). A property name or enum in a table is checked against the official CloudFormation schemas bundled with cfn-lint, so this reference and CloudFormation agree.

For a walk-through, start with [GUIDE.md](GUIDE.md).

## How to read this

Each resource is a \`01\` group in \`WORKING-STORAGE\`. Its first item sets the type, and the other items set properties:

\`\`\`cobol
       01  MAIN-VPC.
           05  RESOURCE-TYPE    PIC X(13) VALUE "AWS::EC2::VPC".
           05  VPC-CIDR         PIC X(11) VALUE "10.0.0.0/16".
\`\`\`

The group name becomes the logical ID in PascalCase (\`MAIN-VPC\` is \`MainVpc\`). Item names are exactly as listed here, in upper case. A misspelled item is an error with a "did you mean" hint; it is never ignored.

**Types**

| Type | What to write |
|---|---|
${Object.entries(KIND)
  .map(([k, v]) => `| ${v} | ${{
    string: "a string literal",
    number: "a numeric item (`PIC 9(n) VALUE 80`)",
    numstr: "a numeric item; CloudFormation receives it as a string",
    bool: "`Y` or `N`",
    ref: "`REF:NAME` for another resource in this file, `GETATT:NAME.ATTR` for an attribute (`ARN` becomes `Arn`), or a literal ID",
    strings: "values separated by commas, each of which may be a `REF:` or `GETATT:`",
    ssm: "`SSM:/path` becomes `{{resolve:ssm:/path}}`, `SECRET:id` becomes `{{resolve:secretsmanager:id}}`, anything else is used as is",
    userdata: "a script as one string; write `\\n` for a newline. It is wrapped in `Fn::Base64`",
    secret: "`SECRET:` or `SSM:` only. A plain-text password is an error",
    targets: "ids separated by commas",
  }[k as Kind]} |`)
  .join("\n")}

${COMMON}

`);

  out.push("## Contents\n");
  out.push("- [Core: S3, IAM, Lambda, DynamoDB](#core-s3-iam-lambda-dynamodb)");
  for (const [, title] of AREAS) out.push(`- [${title}](#${title.toLowerCase().replaceAll(" ", "-")})`);
  out.push("");

  out.push("## Core: S3, IAM, Lambda, DynamoDB\n");
  for (const h of HAND_WRITTEN) {
    out.push(`### ${h.type}\n`);
    out.push(h.markdown);
    out.push("");
  }

  for (const [file, title] of AREAS) {
    const source = sources[file] ?? "";
    out.push(`## ${title}\n`);
    for (const spec of specs.values()) {
      // この型の定義が、このファイルにあるものだけ
      if (!source.includes(`type: "${spec.type}"`)) continue;
      out.push(`### ${spec.type}\n`);
      if (spec.tags) out.push("Takes `NAME-TAG`.\n");
      out.push(spec.fields.length > 0 ? `${HEADER}\n${spec.fields.map(fieldRow).join("\n")}\n` : "No items of its own.\n");
      for (const list of spec.lists ?? []) out.push(`${listBlock(list)}\n`);
      const rules = [...(spec.notes ?? []).map((n) => `- ${n}`), ...rulesFrom(blockOf(source, spec.type))];
      if (rules.length > 0) out.push(`Rules:\n\n${rules.join("\n")}\n`);
    }
  }

  return `${out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}
